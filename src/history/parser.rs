/// Messages shown in a conversation's preview line
const PREVIEW_PARTS: u8 = 3;
/// Characters kept per preview message; more never fit on one line
const PREVIEW_PART_CHARS: usize = 300;

/// User messages starting with one of these are wrappers around slash commands
/// and their output (`/clear`, `/model`, ...), not something the user wrote.
const COMMAND_WRAPPER_PREFIXES: [&str; 3] = [
    "<command-",
    "<local-command-",
    "Caveat: The messages below were generated by the user while running local commands.",
];

/// Everything gathered from a conversation file so far. It is built line by
/// line, so a file that has only grown can be resumed from where parsing
/// stopped instead of being read again from the start.
#[derive(Clone, Default, Serialize, Deserialize)]
pub struct ParseState {
    /// Folded, whitespace-normalized text of all messages (summary not included)
    body: String,
    /// Display text of the first few messages
    preview: String,
    preview_parts: u8,
    seen_real_user_message: bool,
    skip_next_assistant: bool,
    cwd: Option<PathBuf>,
    message_count: usize,
    summary: Option<String>,
    first_ts_ms: Option<i64>,
    last_ts_ms: Option<i64>,
}

impl ParseState {
    /// Text of a message, recording its timestamp. `None` for entries
    /// without a message, timestamp or content.
    fn message_text(
        &mut self,
        message: Option<Message>,
        timestamp: Option<Cow<str>>,
    ) -> Option<String> {
        let timestamp = timestamp?;
        let Content(text) = message?.content?;
        if let Ok(ts) = DateTime::parse_from_rfc3339(&timestamp) {
            let ms = ts.timestamp_millis();
            self.first_ts_ms.get_or_insert(ms);
            self.last_ts_ms = Some(ms);
        }
        Some(text)
    }

    fn push_preview(&mut self, text: &str) {
        if self.preview_parts >= PREVIEW_PARTS {
            return;
        }
        self.preview_parts += 1;
        if !self.preview.is_empty() {
            self.preview.push_str(" ... ");
        }
        let mut kept = 0;
        for word in strip_tags(text).split_whitespace() {
            if kept >= PREVIEW_PART_CHARS {
                break;
            }
            if kept > 0 {
                self.preview.push(' ');
            }
            self.preview.push_str(word);
            kept += word.chars().count() + 1;
        }
    }

    /// Feed one JSONL line; malformed or irrelevant lines are ignored.
    pub fn feed_line(&mut self, line: &[u8]) {
        if line.trim_ascii().is_empty() {
            return;
        }
        let Ok(entry) = serde_json::from_slice::<LogEntry>(line) else {
            return;
        };

        if self.cwd.is_none()
            && let Some(cwd) = &entry.cwd
        {
            self.cwd = Some(PathBuf::from(cwd.as_ref()));
        }

        match entry.kind.as_ref() {
            "user" => {
                let Some(text) = self.message_text(entry.message, entry.timestamp) else {
                    return;
                };
                if text.trim().is_empty() || is_command_wrapper(&text) {
                    return;
                }

                push_folded(&mut self.body, &text);

                let is_warmup = !self.seen_real_user_message && text.trim() == "Warmup";
                if is_warmup {
                    self.skip_next_assistant = true;
                } else {
                    self.message_count += 1;
                    self.push_preview(&text);
                    self.seen_real_user_message = true;
                }
            }
            "assistant" => {
                let Some(text) = self.message_text(entry.message, entry.timestamp) else {
                    return;
                };
                if text.is_empty() {
                    return;
                }

                push_folded(&mut self.body, &text);

                if self.skip_next_assistant {
                    self.skip_next_assistant = false;
                } else if self.seen_real_user_message {
                    self.message_count += 1;
                    self.push_preview(&text);
                }
            }
            "summary" if self.summary.is_none() => {
                self.summary = entry.summary.map(Cow::into_owned);
            }
            _ => {}
        }
    }

    /// Build the conversation, or `None` if it has nothing worth listing.
    /// `fallback_dir` is the project directory used when no entry had a `cwd`.
    pub fn finish(
        &self,
        path: PathBuf,
        modified: Option<SystemTime>,
        fallback_dir: &Path,
    ) -> Option<Conversation> {
        if self.preview_parts == 0 {
            return None;
        }

        // Last message time; mtime changes when files are copied or synced
        let timestamp = self
            .last_ts_ms
            .and_then(DateTime::from_timestamp_millis)
            .map(|t| t.with_timezone(&Local))
            .or_else(|| modified.map(DateTime::<Local>::from))
            .unwrap_or_else(Local::now);

        let mut search_text = String::with_capacity(self.body.len() + 64);
        if let Some(summary) = &self.summary {
            push_folded(&mut search_text, summary);
            search_text.push(' ');
        }
        search_text.push_str(&self.body);

        let duration_minutes = match (self.first_ts_ms, self.last_ts_ms) {
            (Some(first), Some(last)) => {
                let minutes = (last - first) / 60_000;
                (minutes > 0).then_some(minutes as u64)
            }
            _ => None,
        };

        let project_path = self
            .cwd
            .clone()
            .unwrap_or_else(|| fallback_dir.to_path_buf());

        Some(Conversation {
            path,
            timestamp,
            preview: self.preview.clone(),
            search_text,
            project_name: format_short_name_from_path(&project_path),
            project_path,
            message_count: self.message_count,
            summary: self.summary.clone(),
            duration_minutes,
        })
    }
}

/// Parse state together with how far into the file it got. `offset` always
/// sits right after a newline, so parsing can resume there.
#[derive(Clone, Default, Serialize, Deserialize)]
pub struct Progress {
    pub offset: u64,
    pub state: ParseState,
}

/// Continue parsing `reader` (positioned at `progress.offset`) to its end.
/// Returns the state as of the end of the input: a trailing line with no
/// newline yet counts toward it but not toward `progress`, since it may still
/// be in the middle of being written.
fn parse_from<R: BufRead>(progress: &mut Progress, mut reader: R) -> Result<Cow<'_, ParseState>> {
    let mut line: Vec<u8> = Vec::with_capacity(64 * 1024);
    loop {
        line.clear();
        let n = reader.read_until(b'\n', &mut line)?;
        if n == 0 {
            return Ok(Cow::Borrowed(&progress.state));
        }
        if line.last() != Some(&b'\n') {
            let mut state = progress.state.clone();
            state.feed_line(&line);
            return Ok(Cow::Owned(state));
        }
        progress.state.feed_line(&line);
        progress.offset += n as u64;
    }
}

/// Parse a conversation file, resuming from `progress`.
pub fn process_conversation_file(
    path: PathBuf,
    modified: Option<SystemTime>,
    fallback_dir: &Path,
    progress: &mut Progress,
) -> Result<Option<Conversation>> {
    let mut file = File::open(&path)?;
    if progress.offset > 0 && !follows_newline(&mut file, progress.offset)? {
        // The prefix we parsed is no longer there (file rewritten): start over
        *progress = Progress::default();
        file.seek(SeekFrom::Start(0))?;
    }
    let reader = BufReader::with_capacity(256 * 1024, file);
    Ok(parse_from(progress, reader)?.finish(path, modified, fallback_dir))
}

/// Seek to `offset` and report whether the byte just before it is a newline.
fn follows_newline(file: &mut File, offset: u64) -> Result<bool> {
    file.seek(SeekFrom::Start(offset - 1))?;
    let mut byte = [0u8; 1];
    Ok(file.read(&mut byte)? == 1 && byte[0] == b'\n')
}

fn is_command_wrapper(message: &str) -> bool {
    let trimmed = message.trim_start();
    COMMAND_WRAPPER_PREFIXES
        .iter()
        .any(|prefix| trimmed.starts_with(prefix))
}

/// Remove XML-like tags (`<foo>`, `</foo>`), which make previews unreadable
fn strip_tags(text: &str) -> Cow<'_, str> {
    if !text.contains('<') {
        return Cow::Borrowed(text);
    }
    let mut result = String::with_capacity(text.len());
    let mut in_tag = false;
    for c in text.chars() {
        match c {
            '<' => in_tag = true,
            '>' => in_tag = false,
            _ if !in_tag => result.push(c),
            _ => {}
        }
    }
    Cow::Owned(result)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::io::Cursor;

    fn user_msg(text: &str, cwd: Option<&str>) -> String {
        let cwd_json = match cwd {
            Some(c) => format!(r#""cwd": "{}","#, c),
            None => String::new(),
        };
        format!(
            r#"{{"type": "user", "timestamp": "2024-01-01T00:00:00Z", {}  "message": {{"role": "user", "content": "{}"}}}}"#,
            cwd_json, text
        )
    }

    fn assistant_msg(text: &str) -> String {
        format!(
            r#"{{"type": "assistant", "timestamp": "2024-01-01T00:00:00Z", "message": {{"role": "assistant", "content": [{{"type": "text", "text": "{}"}}]}}}}"#,
            text
        )
    }

    fn finish(state: &ParseState) -> Option<Conversation> {
        state.finish(PathBuf::from("test.jsonl"), None, Path::new("/fallback"))
    }

    fn parse_jsonl(content: &str) -> Option<Conversation> {
        let mut progress = Progress::default();
        finish(&parse_from(&mut progress, Cursor::new(content)).unwrap())
    }

    #[test]
    fn filters_warmup_messages() {
        let content = [
            user_msg("Warmup", None),
            assistant_msg("Ready"),
            user_msg("Hello world", None),
            assistant_msg("Hi there"),
        ]
        .join("\n");

        let conv = parse_jsonl(&content).unwrap();
        assert_eq!(conv.message_count, 2);
        assert_eq!(conv.preview, "Hello world ... Hi there");
        assert!(conv.search_text.contains("hello world"));
    }

    #[test]
    fn filters_command_only_conversations() {
        let content = [
            user_msg(
                "Caveat: The messages below were generated by the user while running local commands.",
                None,
            ),
            user_msg("<command-name>/clear</command-name>", None),
            user_msg("<local-command-stdout></local-command-stdout>", None),
        ]
        .join("\n");

        assert!(parse_jsonl(&content).is_none());
    }

    #[test]
    fn skips_commands_in_mixed_conversation() {
        let content = [
            user_msg("Hello", None),
            assistant_msg("Hi"),
            user_msg("<command-name>/clear</command-name>", None),
            user_msg("Another question", None),
        ]
        .join("\n");

        let conv = parse_jsonl(&content).unwrap();
        assert_eq!(conv.search_text, "hello hi another question");
    }

    #[test]
    fn keeps_messages_that_only_mention_tags() {
        let content = user_msg("why does <command-args> get filtered?", None);
        let conv = parse_jsonl(&content).unwrap();
        assert_eq!(conv.preview, "why does get filtered?");
        assert!(conv.search_text.contains("<command-args>"));
    }

    #[test]
    fn project_path_from_first_cwd_else_fallback() {
        let content = [
            user_msg("Hello", Some("/home/user/project")),
            assistant_msg("Hi"),
            user_msg("More", Some("/other/path")),
        ]
        .join("\n");
        let conv = parse_jsonl(&content).unwrap();
        assert_eq!(conv.project_path, PathBuf::from("/home/user/project"));
        assert_eq!(conv.project_name, "project");

        let conv = parse_jsonl(&user_msg("Hello", None)).unwrap();
        assert_eq!(conv.project_path, PathBuf::from("/fallback"));
    }

    #[test]
    fn handles_empty_conversation() {
        assert!(parse_jsonl("").is_none());
    }

    #[test]
    fn counts_messages_correctly() {
        let content = [
            user_msg("First", None),
            assistant_msg("Response 1"),
            user_msg("Second", None),
            assistant_msg("Response 2"),
        ]
        .join("\n");

        assert_eq!(parse_jsonl(&content).unwrap().message_count, 4);
    }

    #[test]
    fn summary_is_extracted_and_searchable() {
        let content = [
            r#"{"type": "summary", "summary": "Important topic discussion", "leafUuid": "abc123"}"#
                .to_string(),
            user_msg("Hello", None),
            assistant_msg("Hi there"),
        ]
        .join("\n");

        let conv = parse_jsonl(&content).unwrap();
        assert_eq!(conv.summary.as_deref(), Some("Important topic discussion"));
        assert!(conv.search_text.contains("important topic discussion"));
    }

    #[test]
    fn skips_non_text_blocks() {
        let content = [
            user_msg("Hello", None),
            r#"{"type":"assistant","timestamp":"2024-01-01T00:00:00Z","message":{"content":[{"type":"tool_use","input":{"text":"secret"}},{"text":"shown","type":"text"}]}}"#.to_string(),
            r#"{"type":"user","timestamp":"2024-01-01T00:00:00Z","message":{"content":[{"type":"tool_result","content":[{"type":"text","text":"tool output"}]}]}}"#.to_string(),
        ]
        .join("\n");

        assert_eq!(parse_jsonl(&content).unwrap().search_text, "hello shown");
    }

    #[test]
    fn preview_is_capped() {
        let long = "word ".repeat(1000);
        let conv = parse_jsonl(&user_msg(&long, None)).unwrap();
        assert!(conv.preview.chars().count() <= PREVIEW_PART_CHARS + 5);
    }

    #[test]
    fn resuming_matches_full_parse() {
        let lines = [
            r#"{"type": "summary", "summary": "Sum", "leafUuid": "x"}"#.to_string(),
            user_msg("Warmup", Some("/p")),
            assistant_msg("Ready"),
            user_msg("First question", None),
            assistant_msg("First answer"),
            user_msg("Second question", None),
            assistant_msg("Second answer"),
        ];
        let full = lines.join("\n") + "\n";
        let expected = parse_jsonl(&full).unwrap();

        // Cut in the middle of a line, as if it were still being written
        let cut = full.find("First answer").unwrap();
        let mut progress = Progress::default();
        let partial =
            finish(&parse_from(&mut progress, Cursor::new(&full[..cut])).unwrap()).unwrap();
        assert!(!partial.search_text.contains("first answer"));
        assert!(full.as_bytes()[progress.offset as usize - 1] == b'\n');

        let rest = &full[progress.offset as usize..];
        let resumed = finish(&parse_from(&mut progress, Cursor::new(rest)).unwrap()).unwrap();
        assert_eq!(progress.offset as usize, full.len());
        assert_eq!(resumed.search_text, expected.search_text);
        assert_eq!(resumed.preview, expected.preview);
        assert_eq!(resumed.message_count, expected.message_count);
        assert_eq!(resumed.project_path, expected.project_path);
        assert_eq!(resumed.summary, expected.summary);
    }

    #[test]
    fn resume_restarts_when_file_was_rewritten() {
        let path = std::env::temp_dir().join(format!(
            "claude-history-rewrite-{}.jsonl",
            std::process::id()
        ));
        let fallback = Path::new("/fallback");
        let old = [
            user_msg("Old question here", None),
            assistant_msg("Old answer"),
        ]
        .join("\n")
            + "\n";
        std::fs::write(&path, &old).unwrap();
        let mut progress = Progress::default();
        process_conversation_file(path.clone(), None, fallback, &mut progress).unwrap();
        assert_eq!(progress.offset as usize, old.len());

        // Rewritten with different, longer content: old offset is mid-line
        let new = [
            user_msg("A completely different and much longer question", None),
            assistant_msg("New answer"),
        ]
        .join("\n")
            + "\n";
        assert!(new.len() > old.len() && new.as_bytes()[old.len() - 1] != b'\n');
        std::fs::write(&path, &new).unwrap();
        let conv = process_conversation_file(path.clone(), None, fallback, &mut progress)
            .unwrap()
            .unwrap();
        std::fs::remove_file(&path).ok();

        assert!(!conv.search_text.contains("old question"));
        assert!(conv.search_text.contains("new answer"));
        assert_eq!(progress.offset as usize, new.len());
    }

    #[test]
    fn timestamp_uses_last_message_time() {
        let full = [user_msg("Question", None), assistant_msg("Answer")].join("\n") + "\n";
        let conv = parse_jsonl(&full).unwrap();
        assert_eq!(
            conv.timestamp.to_utc().to_rfc3339(),
            "2024-01-01T00:00:00+00:00"
        );
    }

    #[test]
    fn detects_command_wrappers() {
        assert!(is_command_wrapper(
            "Caveat: The messages below were generated by the user while running local commands."
        ));
        assert!(is_command_wrapper("<command-name>/clear</command-name>"));
        assert!(is_command_wrapper(
            "  <local-command-stdout></local-command-stdout>"
        ));
        assert!(!is_command_wrapper("Hello <command-name> world"));
    }
}
